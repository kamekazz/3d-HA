"""Room 17 (2F Hallway) -- `Hall2F Floor Planks`, round V3 wave A.

    python floor3.py                 # texture + GLB + place + repaint the slab
    python floor3.py --nopatch       # geometry only

WHAT THE CRITICS SAID, AND WHERE EACH FIX LIVES
-----------------------------------------------
Two of the nine round-1 critics had the floor as their subject and both named
it as the thing that gave the render away in the first two seconds; three more
named it while judging something else.  Their five complaints:

  1 "no plank structure ... you cannot tell where one board ends and the next
     begins"                                   -> the TILE (planktex.py)
  2 "no plank-to-plank variation"              -> the TILE + this piece
  3 "no butt joints, it is sheet goods"        -> the TILE
  4 "no sheen ... the same value at 2 ft as at 25 ft"   -> this piece
  5 "value is inverted / two stops too dark"   -> measured, see VALUE below

1-3 cannot be done in a GLB.  The photographs' clean floor meters mean|d1|
3.2-7.4 at their own 450x600, which is grain at roughly a 0.1 in scale; the
near field runs about 0.013 ft per pixel, so matching it with vertex colour
needs sample spacing near 0.02 ft, which over this room's 113 sq ft is a
quarter of a million vertices -- 30x the whole-room budget.  `roomkit.glb` has
no image-texture API, but the ROOM SLAB does: `rooms.floor_texture`, keyed into
`frontend/js/textures.js`, which ROOM-BRIEF names as the floor-surface lever.
So the fine scale comes from a NEW tile, `plank_grey`, generated by
`planktex.py` -- 12 boards of 8 in over an 8 ft repeat at 96 px/ft, with
micro-bevelled long edges, staggered butt joints two per board per repeat,
per-segment value (sd 3.6%), three periodic grain octaves, mineral streaks and
knots.  A new key, not an edit to `wood`: six other rooms use `wood`, and
`wood` is unusable here anyway (256 px over 2.2 ft, every column CONSTANT down
its length, no joints, and a flat 15%-dark 2 px seam every board -- which is
the "butt-lines read as UV seams" complaint from round 2).

This GLB is then a thin satin WEAR LAYER over that tile, carrying the four
things a repeating tile cannot:

  * SHEEN.  The slab material is hard-coded `roughness 0.9` in house.js, so the
    slab alone can never be satin.  This layer is roughness 0.24 at 34%
    opacity, so the composite is a matte textured floor seen through a glossy
    film -- which is what a satin-finish LVP physically is.  Per-board crown
    (0.0016 ft over 0.667) plus a slow lengthwise undulation break the specular
    into bands running DOWN the boards instead of lying on the floor as one
    sheet.
  * LIGHT FALLOFF.  Baked pools under the five ceiling cans that see this floor
    (positions taken from ceiling2.py's CANS, which were solved by
    un-projecting the saturated blobs through these poses), and fall-off into
    the alcove and the far corners.  In `hallway_looking_towards_stairs` the
    photo's floor runs 127 in the near field and 203 under the can at the
    master-bedroom door -- a factor of 1.6 -- and our floor was one value end
    to end.
  * CONTACT.  A wall-line AO ramp: 0.50 ft to 0.88, with a 0.055 ft hairline at
    0.80 hard against the wall, on every polygon edge except the open stairwell
    cut (light comes UP through that one).  That is the "no occlusion in any
    reentrant corner, no hairline where two materials meet" theme, on the one
    surface that meets every wall in the room.
  * BREAKING THE REPEAT.  The tile repeats every 8 ft.  This layer adds a
    per-board value step (hard, at x = k*8/12, which registers EXACTLY with the
    tile because slab UVs are u = local_x / size) and a slow non-repeating
    lengthwise drift, so the 12-board pattern never reads twice the same.

NO runner contact shadow is baked here: `Hall2F Floor Runner` already carries
its own decal (its GLB spans the full 3.86 ft strip width against a 2.5 ft rug
body).  Two overlapping shadows is the "nested rings" failure.  Wave B owns it.

VALUE -- measured, not taken from the critic
--------------------------------------------
floor_b said "light greige washed oak within about 15% of the wall grey".  The
photographs do not say that.  Clean floor patches against clean wall patches
in the same frame (fmeter3.py):

    photo                             wall   floor  ratio
    hallway_with_white_runner_rug    167.5   119.1  0.711
    hallway_looking_towards_stairs   155.0   127.2  0.821
    two_closed_white_doors_2         168.0   127.1  0.756
    two_closed_white_doors_1         172.2   134.2  0.779

so 0.71-0.82, mean 0.767 -- not 0.85, and the hue is a COOL near-neutral grey
(rgb 128.7/126.4/128.6, 121.5/117.9/124.7), not greige.  The round-1 floor
really was about half the photo's luminance; the build that shipped before this
one had already corrected that, and this one holds the same ratio.  What was
still missing was everything above.
"""

